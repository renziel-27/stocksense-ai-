ALL_STOCKS = [
    {**s, "category": cat}
    for cat, stocks in STOCK_UNIVERSE.items()
    for s in stocks
]

def search_stocks(query: str) -> list:
    q = query.upper().strip()
    return [
        s for s in ALL_STOCKS
        if q in s["symbol"] or q in s["name"].upper()
        or q in s["sector"].upper()
    ][:10]

def get_stock_info(symbol: str) -> dict:
    for s in ALL_STOCKS:
        if s["symbol"] == symbol.upper():
            return s
    return {"symbol": symbol, "name": symbol,
            "sector": "Unknown", "category": "Other"}
